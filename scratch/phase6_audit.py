# - NOT a ring-1/2/3 neighbor of victim H3 (cand_h3_grid_dist > 3)
# - NOT a nearby ATM cell (distance > nth nearest ATM)
# - NOT in hotspot pool
# - NOT a state or random ATM cell
# We can approximate: if cand_h3_grid_dist is very large for a positive,
# it was almost certainly post-hoc injected.

